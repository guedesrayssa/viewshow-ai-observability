"""Read-only subset of the Prometheus HTTP API for preserved scalar series.

This is an evidence viewer, not a Prometheus server or live metric exporter.
Only exact names generated by build.py are supported; arbitrary PromQL is rejected.
"""
import json
from datetime import datetime
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, urlsplit

SERIES = json.loads((Path(__file__).resolve().parent / "series.json").read_text())


def timestamp(raw):
    try:
        return float(raw)
    except ValueError:
        return datetime.fromisoformat(raw.replace("Z", "+00:00")).timestamp()


class Handler(BaseHTTPRequestHandler):
    def reply(self, status, body):
        encoded = json.dumps(body).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(encoded)))
        self.end_headers()
        self.wfile.write(encoded)

    def do_POST(self):
        self.dispatch()

    def do_GET(self):
        self.dispatch()

    def dispatch(self):
        url = urlsplit(self.path)
        params = parse_qs(url.query)
        if self.command == "POST":
            params.update(parse_qs(self.rfile.read(int(self.headers.get("Content-Length", 0))).decode()))
        if url.path.endswith("/status/buildinfo"):
            return self.reply(200, {"status": "success", "data": {"version": "3.0.0", "revision": "evidence-replay"}})
        if url.path.endswith("/labels"):
            return self.reply(200, {"status": "success", "data": ["__name__", "stage"]})
        if url.path.endswith("/label/__name__/values"):
            return self.reply(200, {"status": "success", "data": sorted(SERIES)})
        name = params.get("query", [""])[0]
        if name == "1+1":  # Grafana datasource health check only.
            return self.reply(200, {"status": "success", "data": {"resultType": "scalar", "result": [timestamp(params.get("time", ["0"])[0]), "2"]}})
        if name not in SERIES:
            return self.reply(400, {"status": "error", "errorType": "bad_data", "error": "Only preserved series names are supported; this viewer does not evaluate PromQL"})
        row = SERIES[name]
        if url.path.endswith("/query_range"):
            start = timestamp(params["start"][0])
            end = timestamp(params["end"][0])
            values = [value for value in row["values"] if start <= value[0] <= end]
            result = [{"metric": row["metric"], "values": values}] if values else []
            return self.reply(200, {"status": "success", "data": {"resultType": "matrix", "result": result}})
        if url.path.endswith("/query"):
            now = timestamp(params.get("time", [str(row["values"][-1][0])])[0])
            values = [value for value in row["values"] if value[0] <= now]
            result = [{"metric": row["metric"], "value": values[-1]}] if values else []
            return self.reply(200, {"status": "success", "data": {"resultType": "vector", "result": result}})
        self.reply(404, {"status": "error", "error": "unsupported endpoint"})


if __name__ == "__main__":
    ThreadingHTTPServer(("0.0.0.0", 8080), Handler).serve_forever()
